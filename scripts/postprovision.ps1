#!/usr/bin/env pwsh
# SAHAYA postprovision hook (Windows / PowerShell 7).
# Runs automatically after `azd provision` or `azd up`.
# Writes a local .env for the Python app. Keys are fetched with az CLI at
# run time and written only to .env (gitignored) — never to azd state or git.

$ErrorActionPreference = 'Stop'

Write-Host ''
Write-Host 'SAHAYA: writing local .env from the azd environment...' -ForegroundColor Cyan

# 1. Read every value azd stored from the Bicep outputs.
$values = @{}
foreach ($line in (azd env get-values)) {
    if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"?(.*?)"?\s*$') {
        $values[$Matches[1]] = $Matches[2]
    }
}

$required = @(
    'AZURE_SUBSCRIPTION_ID', 'AZURE_RESOURCE_GROUP', 'AZURE_AI_ACCOUNT_NAME',
    'AZURE_SEARCH_SERVICE_NAME', 'FOUNDRY_PROJECT_ENDPOINT', 'FOUNDRY_MODEL',
    'FOUNDRY_MODELS_ENDPOINT', 'FOUNDRY_EMBEDDING_MODEL', 'SEARCH_ENDPOINT',
    'APPLICATIONINSIGHTS_CONNECTION_STRING'
)
$missing = $required | Where-Object { -not $values.ContainsKey($_) -or [string]::IsNullOrWhiteSpace($values[$_]) }
if ($missing) {
    throw "These azd values are missing (did provisioning finish?): $($missing -join ', ')"
}

# 2. az CLI must be installed and signed in to the same subscription azd used.
if (-not (Get-Command az -ErrorAction SilentlyContinue)) {
    throw 'Azure CLI (az) not found. Install it, run "az login", then run "azd hooks run postprovision".'
}
az account set --subscription $values['AZURE_SUBSCRIPTION_ID'] 2>$null
if ($LASTEXITCODE -ne 0) {
    throw 'az CLI is not signed in to this subscription. Run "az login", then "azd hooks run postprovision".'
}

# 3. Fetch the two keys SAHAYA still uses (see README "Known limitations").
$modelsKey = az cognitiveservices account keys list `
    --name $values['AZURE_AI_ACCOUNT_NAME'] `
    --resource-group $values['AZURE_RESOURCE_GROUP'] `
    --query key1 -o tsv
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($modelsKey)) { throw 'Could not read the Foundry key.' }

$searchKey = az search admin-key show `
    --service-name $values['AZURE_SEARCH_SERVICE_NAME'] `
    --resource-group $values['AZURE_RESOURCE_GROUP'] `
    --query primaryKey -o tsv
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($searchKey)) { throw 'Could not read the AI Search admin key.' }

# 4. Back up any existing .env, then write the new one.
$envPath = Join-Path (Get-Location) '.env'
if (Test-Path $envPath) {
    Copy-Item $envPath "$envPath.bak" -Force
    Write-Host 'Existing .env backed up to .env.bak' -ForegroundColor DarkGray
}

$lines = @(
    '# Generated by the azd postprovision hook. Do not commit this file.',
    "FOUNDRY_PROJECT_ENDPOINT=""$($values['FOUNDRY_PROJECT_ENDPOINT'])""",
    "FOUNDRY_MODEL=""$($values['FOUNDRY_MODEL'])""",
    "FOUNDRY_MODELS_ENDPOINT=""$($values['FOUNDRY_MODELS_ENDPOINT'])""",
    "FOUNDRY_MODELS_API_KEY=""$($modelsKey.Trim())""",
    "FOUNDRY_EMBEDDING_MODEL=""$($values['FOUNDRY_EMBEDDING_MODEL'])""",
    "SEARCH_ENDPOINT=""$($values['SEARCH_ENDPOINT'])""",
    "SEARCH_KEY=""$($searchKey.Trim())""",
    "APPLICATIONINSIGHTS_CONNECTION_STRING=""$($values['APPLICATIONINSIGHTS_CONNECTION_STRING'])"""
)

# UTF-8 WITHOUT a byte-order mark: a BOM would corrupt the first variable
# name when python-dotenv reads the file.
[System.IO.File]::WriteAllLines($envPath, $lines, (New-Object System.Text.UTF8Encoding($false)))

Write-Host '.env written.' -ForegroundColor Green
Write-Host ''
Write-Host 'Next steps:' -ForegroundColor Cyan
Write-Host '  1. Put the SDRF norms PDF and Kerala G.O. PDFs in .\norms\ (see norms\README.md)'
Write-Host '  2. python build_index.py'
Write-Host '  3. python web_demo.py data/sample_claims/claim_clean_en.txt'
Write-Host ''