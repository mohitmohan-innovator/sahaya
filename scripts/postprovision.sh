#!/bin/sh
# SAHAYA postprovision hook (macOS / Linux / Codespaces).
# Runs automatically after `azd provision` or `azd up`.
# Writes a local .env for the Python app. Keys are fetched with az CLI at
# run time and written only to .env (gitignored) — never to azd state or git.
set -eu

echo ""
echo "SAHAYA: writing local .env from the azd environment..."

# 1. Load every value azd stored from the Bicep outputs (KEY="value" lines).
eval "$(azd env get-values)"

for name in AZURE_SUBSCRIPTION_ID AZURE_RESOURCE_GROUP AZURE_AI_ACCOUNT_NAME \
            AZURE_SEARCH_SERVICE_NAME FOUNDRY_PROJECT_ENDPOINT FOUNDRY_MODEL \
            FOUNDRY_MODELS_ENDPOINT FOUNDRY_EMBEDDING_MODEL SEARCH_ENDPOINT \
            APPLICATIONINSIGHTS_CONNECTION_STRING; do
  eval "value=\${$name:-}"
  if [ -z "$value" ]; then
    echo "Missing azd value: $name (did provisioning finish?)" >&2
    exit 1
  fi
done

# 2. az CLI must be installed and signed in to the same subscription azd used.
if ! command -v az >/dev/null 2>&1; then
  echo 'Azure CLI (az) not found. Install it, run "az login", then "azd hooks run postprovision".' >&2
  exit 1
fi
if ! az account set --subscription "$AZURE_SUBSCRIPTION_ID" >/dev/null 2>&1; then
  echo 'az CLI is not signed in to this subscription. Run "az login", then "azd hooks run postprovision".' >&2
  exit 1
fi

# 3. Fetch the two keys SAHAYA still uses (see README "Known limitations").
MODELS_KEY=$(az cognitiveservices account keys list \
  --name "$AZURE_AI_ACCOUNT_NAME" --resource-group "$AZURE_RESOURCE_GROUP" \
  --query key1 -o tsv)
SEARCH_KEY_VALUE=$(az search admin-key show \
  --service-name "$AZURE_SEARCH_SERVICE_NAME" --resource-group "$AZURE_RESOURCE_GROUP" \
  --query primaryKey -o tsv)
if [ -z "$MODELS_KEY" ] || [ -z "$SEARCH_KEY_VALUE" ]; then
  echo "Could not read the Foundry key or the AI Search admin key." >&2
  exit 1
fi

# 4. Back up any existing .env, then write the new one. umask 077 makes both
#    files owner-readable only, since both contain keys.
umask 077
if [ -f .env ]; then
  rm -f .env.bak
  cp .env .env.bak
  echo "Existing .env backed up to .env.bak"
fi

rm -f .env   # recreate (not overwrite) so umask applies to a fresh file
cat > .env <<EOF
# Generated by the azd postprovision hook. Do not commit this file.
FOUNDRY_PROJECT_ENDPOINT="$FOUNDRY_PROJECT_ENDPOINT"
FOUNDRY_MODEL="$FOUNDRY_MODEL"
FOUNDRY_MODELS_ENDPOINT="$FOUNDRY_MODELS_ENDPOINT"
FOUNDRY_MODELS_API_KEY="$MODELS_KEY"
FOUNDRY_EMBEDDING_MODEL="$FOUNDRY_EMBEDDING_MODEL"
SEARCH_ENDPOINT="$SEARCH_ENDPOINT"
SEARCH_KEY="$SEARCH_KEY_VALUE"
APPLICATIONINSIGHTS_CONNECTION_STRING="$APPLICATIONINSIGHTS_CONNECTION_STRING"
EOF

echo ".env written."
echo ""
echo "Next steps:"
echo "  1. Put the SDRF norms PDF and Kerala G.O. PDFs in ./norms/ (see norms/README.md)"
echo "  2. python build_index.py"
echo "  3. python web_demo.py data/sample_claims/claim_clean_en.txt"
echo ""